create table if not exists public.cats (
    id integer generated by default as identity primary key,
    name text not null check (char_length(trim(name)) between 1 and 80),
    breed text not null check (char_length(trim(breed)) between 1 and 100),
    location text not null default '',
    description text not null default '',
    image_url text not null,
    created_at timestamptz not null default now()
);

alter table public.cats enable row level security;

grant select, insert on public.cats to anon, authenticated;
grant usage, select on sequence public.cats_id_seq to anon, authenticated;

drop policy if exists "Anyone can read cat feed" on public.cats;
create policy "Anyone can read cat feed"
    on public.cats for select
    to anon, authenticated
    using (true);

drop policy if exists "Anyone can publish a cat" on public.cats;
create policy "Anyone can publish a cat"
    on public.cats for insert
    to anon, authenticated
    with check (
        image_url like 'https://qzwqelglkxvnkfsrgled.supabase.co/storage/v1/object/public/cat-images/%'
    );

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('cat-images', 'cat-images', true, 10485760, array['image/jpeg'])
on conflict (id) do update set public = excluded.public;

drop policy if exists "Anyone can upload cat photos" on storage.objects;
create policy "Anyone can upload cat photos"
    on storage.objects for insert
    to anon, authenticated
    with check (bucket_id = 'cat-images');
